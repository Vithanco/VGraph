extension Notations {

    /// Future Reality Tree (FRT) is a planning and solution validation tool from Theory of Constraints.
    /// It uses "If...Then..." logic to answer "TO WHAT should we change?" by modeling cause-and-effect
    /// relationships between proposed solutions (injections) and desired outcomes.
    /// Unlike CRT which starts with problems, FRT starts with solutions and builds upward to show
    /// how those solutions lead to desirable effects.
    public struct FutureRealityTree: NotationDeclaration {

        public static var criteria: [QualityCheckSpec] { [.noParallelEdges] }
        public static let id: Identifier<Notation> = .init(rawValue: "FRT")
        public static let description =
            "Validates proposed solutions by projecting their cause-and-effect consequences forward to confirm they produce Desirable Effects without new problems, answering 'To what should we change?'"
        public static var diagramLogic: DiagramLogic { .sufficientCause }

        // MARK: - Self-description

        public static let purpose: String = """
            The Future Reality Tree takes proposed solutions (Injections) — typically generated by \
            the Evaporating Cloud — and projects their cause-and-effect consequences forward. Each \
            link uses "If… then…" sufficient-cause logic, so the tree shows whether the injections \
            produce Desirable Effects and whether they introduce any new Undesirable Effects \
            (Negative Branches). The FRT answers the second TOC question: "To what should we change?"
            """

        public static let whenToUse: [String] = [
            "Validating a proposed solution before committing resources: will it actually produce the desired outcomes?",
            "Detecting negative branches: unintended consequences that the proposed change might introduce.",
            "Building the case for a change: giving stakeholders a traceable logical argument for the expected benefits.",
            "After the Evaporating Cloud: translating the winning injection into a full cause-and-effect scenario.",
            "As the second step in a full TOC Thinking Process sequence (after CRT and EC, before PRT and TRT).",
        ]

        public static let history: String = """
            The Future Reality Tree is one of the five Thinking Process tools developed by \
            Eliyahu Goldratt as part of Theory of Constraints. It was formalised in "It's Not \
            Luck" (1994) and is described systematically in H. William Dettmer's "The Logical \
            Thinking Process" (2007). The FRT complements the CRT: where the CRT diagnoses the \
            current state, the FRT designs the desired future state.
            """

